package reporter

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/alexandrmotologa/ragfuzz/internal/analyzer"
	"github.com/alexandrmotologa/ragfuzz/internal/fuzzer"
	"github.com/alexandrmotologa/ragfuzz/internal/runner"
)

// GenerateGitHubMarkdown writes a formatted Markdown summary suitable for GitHub PR comments and $GITHUB_STEP_SUMMARY.
func GenerateGitHubMarkdown(filePath string, session *runner.SessionState) error {
	dir := filepath.Dir(filePath)
	if dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0755); err != nil {
			return err
		}
	}

	summary := session.Summary
	if summary == nil {
		return fmt.Errorf("session summary is nil")
	}

	var sb strings.Builder

	// Header & Status
	sb.WriteString("## 🛡️ ragfuzz :: Adversarial RAG Quality Gate\n\n")

	if summary.GatePassed {
		sb.WriteString("> **CI/CD Quality Gate:** :white_check_mark: **PASSED** (All reliability criteria satisfied)\n\n")
	} else {
		sb.WriteString("> **CI/CD Quality Gate:** :x: **FAILED** (Reliability thresholds breached)\n\n")
		if len(summary.GateBreaches) > 0 {
			sb.WriteString("**Breached Thresholds:**\n")
			for _, b := range summary.GateBreaches {
				sb.WriteString(fmt.Sprintf("- ⚠️ %s\n", b))
			}
			sb.WriteString("\n")
		}
	}

	// Scorecard Table
	sb.WriteString("### 📊 Metrics Scorecard\n\n")
	sb.WriteString("| Metric | Value | Target Threshold | Status |\n")
	sb.WriteString("| :--- | :--- | :--- | :--- |\n")
	sb.WriteString(fmt.Sprintf("| **Pass Rate** | `%.1f%%` (%d/%d) | - | %s |\n",
		summary.PassRate*100, summary.PassedQueries, summary.TotalQueries, getMarkdownStatusBadge(summary.PassRate >= 0.85)))
	sb.WriteString(fmt.Sprintf("| **Groundedness (NLI)** | `%.1f%%` | &ge; `%.1f%%` | %s |\n",
		summary.MeanGroundedness*100, session.Thresholds.MinGroundedness*100, getMarkdownStatusBadge(summary.MeanGroundedness >= session.Thresholds.MinGroundedness)))
	sb.WriteString(fmt.Sprintf("| **Recall Degradation** | `%.1f%%` | &le; `%.1f%%` | %s |\n",
		summary.RecallDegradation*100, session.Thresholds.MaxRecallDegradation*100, getMarkdownStatusBadge(summary.RecallDegradation <= session.Thresholds.MaxRecallDegradation)))
	sb.WriteString(fmt.Sprintf("| **Refusal Calibration F1** | `%.2f` | &ge; `%.2f` | %s |\n",
		summary.RefusalF1, session.Thresholds.MinRefusalF1, getMarkdownStatusBadge(summary.RefusalF1 >= session.Thresholds.MinRefusalF1)))
	sb.WriteString(fmt.Sprintf("| **Distractor Intrusions** | `%d` | `0` | %s |\n",
		summary.DistractorIntrusions, getMarkdownStatusBadge(summary.DistractorIntrusions == 0)))
	sb.WriteString("\n")

	// 6-Axis Breakdown Table
	sb.WriteString("### 🎯 6-Axis Attack Vector Robustness\n\n")
	sb.WriteString("| Vector | Total | Pass | Fail | Robustness | Status |\n")
	sb.WriteString("| :--- | :--- | :--- | :--- | :--- | :--- |\n")

	for _, vec := range fuzzer.AllVectors {
		tot := session.VectorTotal[vec]
		pass := session.VectorPass[vec]
		fail := tot - pass
		score := summary.VectorScores[vec]

		statusBadge := ":white_check_mark: PASS"
		if score < 75.0 {
			statusBadge = ":x: FAIL"
		} else if score < 90.0 {
			statusBadge = ":warning: WARN"
		}

		sb.WriteString(fmt.Sprintf("| **%s** | %d | %d | %d | `%.1f%%` | %s |\n",
			formatVectorName(vec), tot, pass, fail, score, statusBadge))
	}
	sb.WriteString("\n")

	// Failed Queries Highlights
	if summary.FailedQueries > 0 {
		sb.WriteString("<details><summary><b>⚠️ Critical Failure Highlights (Top 5)</b></summary>\n\n")
		sb.WriteString("| ID | Vector | Adversarial Query | Failure Reason |\n")
		sb.WriteString("| :--- | :--- | :--- | :--- |\n")

		count := 0
		for _, ev := range session.Evaluations {
			if !ev.Passed {
				sb.WriteString(fmt.Sprintf("| `%s` | `%s` | %s | %s |\n",
					ev.TestCase.ID, ev.TestCase.Vector, escapeMarkdownCell(ev.TestCase.MutatedQuery), escapeMarkdownCell(ev.FailureReason)))
				count++
				if count >= 5 {
					break
				}
			}
		}
		sb.WriteString("\n</details>\n\n")
	}

	// Architectural Recommendations
	recs := analyzer.GenerateRecommendations(summary)
	if len(recs) > 0 {
		sb.WriteString("### 💡 Recommended Mitigations\n\n")
		for _, r := range recs {
			sb.WriteString(fmt.Sprintf("- **%s** (`%s`): %s\n  *Action:* `%s`\n",
				r.Title, r.Severity, r.ActionPlan, r.SuggestedFix))
		}
		sb.WriteString("\n")
	}

	sb.WriteString("---\n*Generated by [ragfuzz](https://github.com/alexandrmotologa/ragfuzz) :: Automated Adversarial Stress Testing Engine for Production RAG*\n")

	return os.WriteFile(filePath, []byte(sb.String()), 0644)
}

func getMarkdownStatusBadge(passed bool) string {
	if passed {
		return ":white_check_mark: PASS"
	}
	return ":x: FAIL"
}

func escapeMarkdownCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}
